function usage(exitCode = 0): never {
  console.log(`Usage: bivy plugin <command> [options]

Develop, install, and inspect declarative Bivy plugins.

A plugin adds agents, chat widgets, tools, themes or guides. It is a folder
with a bivy.plugin.yaml; agents write and install them for the user.

Commands:
  init [directory]         Scaffold a plugin (--kind widget|tool|theme|guide|agent)
  validate <path>          Validate a bivy.plugin.yaml/json manifest
  doctor <path>            Check compatibility and adapter executables
  test <path>              Run static checks and live ACP handshakes
  install <source> [--force]
                           Install from a folder, a manifest, a git URL or
                           github:owner/repo[/path][#ref]
  dev <directory>          Install, then reinstall on every change
  list [--json]            List installed plugins and diagnostics
  remove <id>              Remove an installed plugin

Also: bivy tools list|run (plugin tools), bivy theme list|set|clear.

Options:
  --kind <kind>            What init scaffolds (default: agent)
  --adapter <acp|process>  Adapter generated by init (default: acp)
  --id <slug>              Plugin id generated by init
  --name <name>            Display name generated by init
  --json                   Emit machine-readable JSON
  --force                  Replace an installed plugin with the same id

Plugin test never prompts a process adapter: that could spend money or mutate a
workspace. It verifies the executable and static contract. ACP adapters must
complete initialize and session/new through Bivy's real bridge.`);
  process.exit(exitCode);
}

function outputJson(value: unknown): void {
  console.log(JSON.stringify(value, null, 2));
}

function option(args: string[], name: string): string | undefined {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

function positionalArgs(args: string[]): string[] {
  const valued = new Set(["--adapter", "--id", "--name", "--kind", "--input"]);
  const out: string[] = [];
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index]!;
    if (valued.has(arg)) { index += 1; continue; }
    if (!arg.startsWith("-")) out.push(arg);
  }
  return out;
}

function fail(error: unknown, json: boolean): never {
  const message = error instanceof Error ? error.message : String(error);
  if (json) outputJson({ ok: false, error: message });
  else console.error(`error: ${message}`);
  process.exit(1);
}

/**
 * What `init --kind` writes: the manifest's `contributes` block and any files
 * beside it. Each kind is a row; every one installs and works as written, so an
 * agent edits a working plugin rather than an empty one.
 */
const SCAFFOLDS: Record<string, (id: string, name: string, adapter: string) => { contributes: string; files: Record<string, string>; next: string }> = {
  agent: (id, name, adapter) => ({
    contributes: `  agents:
    - id: ${id}
      name: ${JSON.stringify(name)}
      authOwner: agent
      adapter:
        kind: ${adapter}
        command: ${id}
${adapter === "process" ? "        promptMode: stdin\n" : "        args: [acp]\n"}`,
    files: {},
    next: "set the adapter command, then run 'bivy plugin doctor' and 'bivy plugin test'",
  }),
  widget: (id, name) => ({
    contributes: `  widgets:
    - id: ${id}
      name: ${JSON.stringify(name)}
      entry: widgets/${id}.html
`,
    files: { [`widgets/${id}.html`]: fs.readFileSync(widgetTemplatePath(), "utf8").replaceAll("::view{src=PATH}", `\`\`\`bivy {"type":"widget","widget":"${id}"}\`\`\``).replaceAll("\"url\":\"PATH\"", `"widget":"${id}"`) },
    next: `edit widgets/${id}.html, install, then place it with \`\`\`bivy {"type":"widget","widget":"${id}","data":{…}}\`\`\``,
  }),
  tool: (id) => {
    const tool = id.replace(/-/g, "_");
    return {
      contributes: `  tools:
    - name: ${tool}
      description: Say hello. Replace with what the tool does and when an agent should call it.
      input:
        name: { type: string, description: Who to greet., required: true }
      command: node
      args: ["{plugin}/tools/${id}.mjs"]
      widgets: true
`,
      files: {
        [`tools/${id}.mjs`]: `// A Bivy plugin tool: JSON input on stdin, JSON (or text) answer on stdout.
// Runs in the session's workspace; a non-zero exit is an error.
let input = "";
for await (const chunk of process.stdin) input += chunk;
const { name } = JSON.parse(input || "{}");
console.log(JSON.stringify({ greeting: \`Hello, \${name}!\` }));
`,
      },
      next: `edit tools/${id}.mjs, install, then try 'bivy tools run ${tool} --input '{"name":"you"}''`,
    };
  },
  theme: (id, name) => ({
    contributes: `  themes:
    - id: ${id}
      name: ${JSON.stringify(name)}
      mode: dark
      colors:
        background: "#1a1b26"
        foreground: "#c0caf5"
        accent: "#7aa2f7"
        muted: "#565f89"
        red: "#f7768e"
        green: "#9ece6a"
        yellow: "#e0af68"
`,
    files: {},
    next: `edit the colors, install, then 'bivy theme set ${id}'`,
  }),
  guide: (id, name) => ({
    contributes: `  guides:
    - topic: ${id}
      file: guides/${id}.md
`,
    files: { [`guides/${id}.md`]: `# ${name}\n\nSummary: One line on when an agent should read this.\n\nThe steps, commands and conventions an agent should follow.\n` },
    next: `edit guides/${id}.md, install, then 'bivy guide ${id}'`,
  }),
};

function widgetTemplatePath(): string {
  // bin/templates sits beside src/ and dist/ alike.
  return path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "bin", "templates", "widget.html");
}

function scaffold(args: string[], json: boolean): void {
  const positional = positionalArgs(args);
  const directory = path.resolve(positional[0] ?? ".");
  const inferred = path.basename(directory).toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  const id = (option(args, "--id") ?? inferred).toLowerCase();
  if (!/^[a-z][a-z0-9-]{1,47}$/.test(id)) throw new Error("Use --id with a lowercase slug of 2-48 characters");
  const adapter = option(args, "--adapter") ?? "acp";
  if (adapter !== "acp" && adapter !== "process") throw new Error("--adapter must be acp or process");
  const kind = option(args, "--kind") ?? "agent";
  const make = SCAFFOLDS[kind];
  if (!make) throw new Error(`--kind must be one of ${Object.keys(SCAFFOLDS).join(", ")}`);
  const name = option(args, "--name") ?? id.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(" ");
  const file = path.join(directory, "bivy.plugin.yaml");
  if (fs.existsSync(file)) throw new Error(`${file} already exists`);
  const scaffolded = make(id, name, adapter);
  fs.mkdirSync(directory, { recursive: true });
  const manifest = `# yaml-language-server: $schema=https://raw.githubusercontent.com/bivysh/bivy/main/packages/plugin-sdk/schema/bivy.plugin.schema.json
apiVersion: bivy.sh/v1alpha1
kind: Plugin
metadata:
  id: ${id}
  name: ${JSON.stringify(name)}
  version: 0.1.0
requires:
  bivy: ${JSON.stringify(recommendedBivyRange(currentBivyVersion()))}
contributes:
${scaffolded.contributes}`;
  fs.writeFileSync(file, manifest, { flag: "wx", mode: 0o644 });
  for (const [relative, content] of Object.entries(scaffolded.files)) {
    const target = path.join(directory, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, { flag: "wx" });
  }
  const body = { ok: true, directory, manifest: file, files: Object.keys(scaffolded.files), plugin: { id, name, kind, ...(kind === "agent" ? { adapter } : {}) }, next: scaffolded.next };
  if (json) outputJson(body);
  else {
    console.log(`Created ${file}${body.files.length ? ` and ${body.files.join(", ")}` : ""}`);
    console.log(`Next: ${scaffolded.next}. 'bivy plugin dev ${directory}' reinstalls on every change.`);
  }
}

/**
 * Where to install from. A folder or manifest as-is; a git URL or
 * `github:owner/repo[/path][#ref]` is cloned (shallow) into a temporary folder
 * first, so sharing a plugin is sharing a repository.
 */
function resolveSource(input: string): { path: string; cleanup: () => void } {
  const github = /^github:([\w.-]+)\/([\w.-]+)((?:\/[\w.-]+)*)(?:#([\w./-]+))?$/.exec(input);
  const git = /^(https:\/\/|git@)[^\s]+?(?:#([\w./-]+))?$/.exec(input);
  if (!github && !(git && (input.endsWith(".git") || input.includes(".git#") || input.startsWith("git@") || /^https:\/\/(github|gitlab)\.com\//.test(input)))) {
    return { path: input, cleanup: () => {} };
  }
  const url = github ? `https://github.com/${github[1]}/${github[2]}.git` : input.replace(/#.*$/, "");
  const ref = github ? github[4] : git?.[2];
  const sub = github?.[3]?.replace(/^\//, "") ?? "";
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "bivy-plugin-src-"));
  try {
    execFileSync("git", ["clone", "--quiet", "--depth", "1", ...(ref ? ["--branch", ref] : []), "--", url, temp], { stdio: ["ignore", "ignore", "pipe"], timeout: 120_000 });
  } catch (error) {
    fs.rmSync(temp, { recursive: true, force: true });
    const detail = (error as { stderr?: Buffer }).stderr?.toString().trim();
    throw new Error(`Could not clone ${url}${detail ? `: ${detail}` : ""}`);
  }
  return { path: path.join(temp, sub), cleanup: () => fs.rmSync(temp, { recursive: true, force: true }) };
}

/** Install now, then again whenever a file in the folder changes. */
async function dev(directory: string, dataDir: string): Promise<void> {
  const root = path.resolve(directory);
  const install = (why: string) => {
    try {
      const result = installPlugin(root, { dataDir, force: true });
      console.log(`${new Date().toLocaleTimeString()} ${why}: installed ${result.manifest.metadata.id}@${result.manifest.metadata.version}`);
    } catch (error) {
      console.error(`${new Date().toLocaleTimeString()} ${why}: ${error instanceof Error ? error.message : String(error)}`);
    }
  };
  install("start");
  console.log(`Watching ${root}. Widgets, tools and guides take effect as soon as they install; press Ctrl-C to stop.`);
  let timer: NodeJS.Timeout | undefined;
  const watcher = fs.watch(root, { recursive: true }, (_event, file) => {
    if (file && String(file).split(path.sep).some((part) => part.startsWith("."))) return;
    clearTimeout(timer);
    timer = setTimeout(() => install(`changed ${file ?? ""}`.trim()), 200);
  });
  await new Promise<void>((resolve) => {
    process.once("SIGINT", () => { watcher.close(); resolve(); });
    process.once("SIGTERM", () => { watcher.close(); resolve(); });
  });
}

/** `bivy tools list|run`: what plugins add for agents to call. */
async function tools(args: string[], json: boolean, dataDir: string): Promise<void> {
  const [sub, ...rest] = args;
  if (!sub || sub === "list" || sub === "ls") {
    const { items, errors } = installedContributions("tools", dataDir);
    const body = { ok: errors.length === 0, tools: items.map(({ pluginId, item }) => ({ name: item.name, description: item.description, plugin: pluginId, widgets: Boolean(item.widgets), inputSchema: toolInputSchema(item) })), errors };
    if (json) outputJson(body);
    else if (!items.length) console.log("No plugin tools installed. An agent can make one: bivy plugin init <dir> --kind tool");
    else for (const tool of body.tools) console.log(`  ${tool.name}  ${tool.description}  (${tool.plugin})`);
    for (const error of errors) console.error(`warning: ${error}`);
    return;
  }
  if (sub !== "run" && sub !== "call") throw new Error("Usage: bivy tools list | bivy tools run <name> [--input '<json>'] [key=value …]");
  const name = positionalArgs(rest)[0];
  if (!name) throw new Error("Usage: bivy tools run <name> [--input '<json>'] [key=value …]");
  const tool = findContribution("tools", name, dataDir);
  if (!tool) throw new Error(`No plugin tool called "${name}". See: bivy tools list`);
  let input: Record<string, unknown> = {};
  const raw = option(rest, "--input");
  if (raw) {
    const parsed = JSON.parse(raw) as unknown;
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("--input must be a JSON object");
    input = parsed as Record<string, unknown>;
  }
  for (const pair of positionalArgs(rest).slice(1)) {
    const at = pair.indexOf("=");
    if (at < 1) throw new Error(`Expected key=value, got "${pair}"`);
    const value = pair.slice(at + 1);
    const type = tool.item.input?.[pair.slice(0, at)]?.type;
    input[pair.slice(0, at)] = type === "number" ? Number(value) : type === "boolean" ? value === "true" : type === "array" || type === "object" ? JSON.parse(value) : value;
  }
  const result = await runPluginTool(tool, input, { cwd: process.cwd(), sessionId: process.env.BIVY_SESSION_ID });
  if (json) outputJson({ ok: true, ...result });
  else console.log(result.content.map((block) => block.text).join("\n"));
}

/** `bivy theme list|set|clear`: choose the app's palette from installed plugins. */
function theme(args: string[], json: boolean, dataDir: string): void {
  const [sub, ...rest] = args;
  const current = selectedThemeId(dataDir);
  if (!sub || sub === "list" || sub === "ls") {
    const { items, errors } = installedContributions("themes", dataDir);
    const body = { ok: errors.length === 0, current, themes: items.map(({ pluginId, item }) => ({ id: item.id, name: item.name, mode: item.mode ?? null, plugin: pluginId })), errors };
    if (json) outputJson(body);
    else if (!items.length) console.log("No plugin themes installed. An agent can make one: bivy plugin init <dir> --kind theme");
    else for (const entry of body.themes) console.log(`${entry.id === current ? "*" : " "} ${entry.id}  ${entry.name}  (${entry.plugin})`);
    return;
  }
  if (sub === "clear" || sub === "reset") {
    selectTheme(dataDir, null);
    if (json) outputJson({ ok: true, current: null });
    else console.log("Back to the machine's own theme. The app updates in a moment.");
    return;
  }
  if (sub !== "set") throw new Error("Usage: bivy theme list | bivy theme set <id> | bivy theme clear");
  const id = positionalArgs(rest)[0];
  const found = id ? findContribution("themes", id, dataDir) : undefined;
  if (!found) throw new Error(`No installed theme called "${id ?? ""}". See: bivy theme list`);
  selectTheme(dataDir, found.item);
  if (json) outputJson({ ok: true, current: found.item.id });
  else console.log(`Theme set to ${found.item.name}. The app follows when its theme is "Machine" (the default).`);
}

/** One line per contribution type, for people and agents reading the output. */
function contributionSummary(manifest: PluginManifest): Record<string, string[]> {
  const c = manifest.contributes;
  return Object.fromEntries(Object.entries({
    agents: c.agents.map((agent) => `${agent.id} [${agent.adapter.kind}]`),
    widgets: (c.widgets ?? []).map((widget) => widget.id),
    tools: (c.tools ?? []).map((tool) => tool.name),
    themes: (c.themes ?? []).map((entry) => entry.id),
    guides: (c.guides ?? []).map((guide) => guide.topic),
  }).filter(([, list]) => list.length));
}

function manifestSummary(file: string, manifest: PluginManifest): Record<string, unknown> {
  return {
    ok: true,
    file,
    plugin: { id: manifest.metadata.id, name: manifest.metadata.name, version: manifest.metadata.version },
    compatibility: checkPluginCompatibility(manifest, currentBivyVersion()),
    contributions: contributionSummary(manifest),
  };
}

async function testPlugin(input: string): Promise<{ ok: boolean; file: string; checks: unknown[]; errors: string[]; warnings: string[] }> {
  const { file, manifest } = readPluginManifest(input);
  const diagnosis = doctorPluginManifest(manifest, { bivyVersion: currentBivyVersion(), cwd: path.dirname(file) });
  const checks: Array<{ name: string; status: "pass" | "warning" | "fail"; message: string; agentId?: string }> = [...diagnosis.checks];
  const errors = [...diagnosis.errors];
  if (!diagnosis.ok) return { ok: false, file, checks, errors, warnings: diagnosis.warnings };

  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "bivy-plugin-test-"));
  const previousDir = process.env.BIVY_PLUGIN_DIR;
  process.env.BIVY_PLUGIN_DIR = path.join(temp, "plugins");
  try {
    installPlugin(file, { dataDir: temp, bivyVersion: currentBivyVersion() });
    const runtimeModule = await import("./runtime/index.js");
    const conflicts = runtimeModule.pluginAgentConflictDiagnostics();
    if (conflicts.length) errors.push(...conflicts);
    if (!errors.length) {
      for (const agent of manifest.contributes.agents) {
        if (agent.adapter.kind === "process") {
          checks.push({ name: "conformance", agentId: agent.id, status: "pass", message: "Static process-adapter conformance passed" });
          continue;
        }
        let session: { dispose(): void } | undefined;
        let timer: NodeJS.Timeout | undefined;
        try {
          const runtime = runtimeModule.makeRuntime({
            runtime: agent.id,
            credsDir: path.join(temp, "credentials"),
            piDir: path.join(temp, "pi"),
            sessionsDir: path.join(temp, "sessions"),
          });
          await Promise.race([
            (async () => {
              const opened = await runtime.createSession({ workspace: path.dirname(file) });
              session = opened.session;
              const open = (opened.session as unknown as { open?: () => Promise<void> }).open;
              if (typeof open !== "function") throw new Error("ACP runtime does not expose the conformance handshake");
              await open.call(opened.session);
            })(),
            new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error("ACP handshake timed out after 15 seconds")), 15_000); }),
          ]);
          checks.push({ name: "conformance", agentId: agent.id, status: "pass", message: "ACP initialize and session/new handshake passed" });
        } catch (error) {
          const message = error instanceof Error ? error.message : String(error);
          errors.push(`${agent.id}: ${message}`);
          checks.push({ name: "conformance", agentId: agent.id, status: "fail", message });
        } finally {
          if (timer) clearTimeout(timer);
          session?.dispose();
        }
      }
    }
  } finally {
    if (previousDir === undefined) delete process.env.BIVY_PLUGIN_DIR;
    else process.env.BIVY_PLUGIN_DIR = previousDir;
    fs.rmSync(temp, { recursive: true, force: true });
  }
  return { ok: errors.length === 0, file, checks, errors, warnings: diagnosis.warnings };
}

export async function main(argv = process.argv.slice(2)): Promise<void> {
  const [command, ...args] = argv;
  if (!command || command === "help" || command === "--help" || command === "-h" || args.includes("--help") || args.includes("-h")) usage();
  const json = args.includes("--json");
  const positional = positionalArgs(args);
  const dataDir = defaultDataDir();

  try {
    if (command === "init") {
      scaffold(args, json);
      return;
    }

    if (command === "validate") {
      const input = positional[0];
      if (!input) fail("Usage: bivy plugin validate <path>", json);
      const { file, manifest } = readPluginManifest(input);
      const result = manifestSummary(file, manifest);
      if (json) outputJson(result);
      else {
        console.log(`Valid plugin: ${manifest.metadata.name} (${manifest.metadata.id}@${manifest.metadata.version})`);
        console.log((result.compatibility as { message: string }).message);
        for (const [key, list] of Object.entries(contributionSummary(manifest))) console.log(`${key[0]!.toUpperCase()}${key.slice(1)}: ${list.join(", ")}`);
      }
      return;
    }

    if (command === "doctor") {
      const input = positional[0];
      if (!input) fail("Usage: bivy plugin doctor <path>", json);
      const { file, manifest } = readPluginManifest(input);
      const result = doctorPluginManifest(manifest, { bivyVersion: currentBivyVersion(), cwd: path.dirname(file) });
      const body = { ...result, file, plugin: manifest.metadata.id };
      if (json) outputJson(body);
      else {
        for (const check of result.checks) console.log(`${check.status === "pass" ? "✓" : check.status === "warning" ? "!" : "✗"} ${check.name}${check.agentId ? ` (${check.agentId})` : ""}: ${check.message}`);
      }
      if (!result.ok) process.exitCode = 1;
      return;
    }

    if (command === "test") {
      const input = positional[0];
      if (!input) fail("Usage: bivy plugin test <path>", json);
      const body = await testPlugin(input);
      if (json) outputJson(body);
      else {
        for (const check of body.checks as Array<{ status: string; name: string; agentId?: string; message: string }>) console.log(`${check.status === "pass" ? "✓" : check.status === "warning" ? "!" : "✗"} ${check.name}${check.agentId ? ` (${check.agentId})` : ""}: ${check.message}`);
        for (const error of body.errors) console.error(`error: ${error}`);
      }
      if (!body.ok) process.exitCode = 1;
      return;
    }

    if (command === "install" || command === "add") {
      const input = positional[0];
      if (!input) fail("Usage: bivy plugin install <folder|manifest|git URL|github:owner/repo[/path][#ref]> [--force]", json);
      const source = resolveSource(input);
      let result: ReturnType<typeof installPlugin>;
      try {
        result = installPlugin(source.path, { dataDir, force: args.includes("--force") });
      } finally {
        source.cleanup();
      }
      const contributions = contributionSummary(result.manifest);
      const body = { ok: true, installed: result.manifest.metadata.id, version: result.manifest.metadata.version, path: result.path, replaced: result.replaced, contributions };
      if (json) outputJson(body);
      else {
        console.log(`${result.replaced ? "Updated" : "Installed"} ${result.manifest.metadata.name} (${result.manifest.metadata.id}@${result.manifest.metadata.version}).`);
        console.log(`Stored at ${result.path}`);
        for (const [key, list] of Object.entries(contributions)) console.log(`${key[0]!.toUpperCase()}${key.slice(1)}: ${list.join(", ")}`);
        if (contributions.agents) console.log("Its agents are in the agent picker now.");
        if (contributions.themes) console.log("Choose a theme with: bivy theme set <id>");
      }
      return;
    }

    if (command === "dev") {
      const input = positional[0];
      if (!input) fail("Usage: bivy plugin dev <directory>", json);
      await dev(input, dataDir);
      return;
    }

    if (command === "tools") {
      await tools(args, json, dataDir);
      return;
    }

    if (command === "theme") {
      theme(args, json, dataDir);
      return;
    }

    if (command === "list" || command === "ls") {
      const plugins = listInstalledPlugins(dataDir);
      const runtimeModule = await import("./runtime/index.js");
      const conflicts = runtimeModule.pluginAgentConflictDiagnostics(dataDir);
      const body = {
        ok: conflicts.length === 0 && plugins.every((plugin) => plugin.errors.length === 0),
        directory: pluginStoreDir(dataDir),
        plugins: plugins.map((plugin) => ({
          id: plugin.id,
          name: plugin.manifest?.metadata.name,
          version: plugin.manifest?.metadata.version,
          agents: plugin.manifest?.contributes.agents.map((agent) => ({ id: agent.id, adapter: agent.adapter.kind })) ?? [],
          contributions: plugin.manifest ? contributionSummary(plugin.manifest) : {},
          status: plugin.errors.length ? "invalid" : "installed",
          errors: plugin.errors,
        })),
        errors: conflicts,
      };
      if (json) outputJson(body);
      else if (!plugins.length) console.log(`No plugins installed. Store: ${body.directory}`);
      else {
        console.log(`Plugins (${body.directory})`);
        for (const plugin of body.plugins) {
          const detail = plugin.status === "installed"
            ? `${plugin.name} ${plugin.version} · ${Object.entries(plugin.contributions).map(([key, list]) => `${key}: ${list.join(", ")}`).join(" · ")}`
            : `invalid · ${plugin.errors.join("; ")}`;
          console.log(`  ${plugin.id}: ${detail}`);
        }
        for (const error of body.errors) console.error(`  warning: ${error}`);
      }
      if (!body.ok) process.exitCode = 1;
      return;
    }

    if (command === "remove" || command === "rm" || command === "uninstall") {
      const id = positional[0];
      if (!id) fail("Usage: bivy plugin remove <id>", json);
      const removed = removePlugin(id, dataDir);
      if (!removed) fail(`Plugin ${id} is not installed`, json);
      const body = { ok: true, removed: id };
      if (json) outputJson(body);
      else {
        console.log(`Removed plugin ${id}.`);
      }
      return;
    }

    usage(1);
  } catch (error) {
    fail(error, json);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
